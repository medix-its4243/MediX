CREATE TABLE IF NOT EXISTS appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL,
    doctor_id BIGINT NOT NULL,
    date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    status VARCHAR(20) NOT NULL,
    reason VARCHAR(255),
    CONSTRAINT appointments_time_order CHECK (start_time < end_time)
);
CREATE INDEX IF NOT EXISTS appointments_patient_idx ON appointments (patient_id, date DESC);
CREATE INDEX IF NOT EXISTS appointments_doctor_day_idx ON appointments (doctor_id, date, status);
